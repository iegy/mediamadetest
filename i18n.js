let currentLang = localStorage.getItem("mm_lang") || "ar";
if (currentLang !== "ar" && currentLang !== "en") currentLang = "ar";

export function getLang() {
  return currentLang;
}

// t(key) أو t(key, {name: "..."}) لو فيه {placeholders} جوه النص
export function t(key, vars) {
  const str = (STRINGS[currentLang] && STRINGS[currentLang][key]) || STRINGS.ar[key] || key;
  if (!vars) return str;
  return Object.keys(vars).reduce((s, k) => s.replace(`{${k}}`, vars[k]), str);
}

export function applyDirection() {
  document.documentElement.lang = currentLang === "en" ? "en" : "ar";
  document.documentElement.dir = currentLang === "en" ? "ltr" : "rtl";
}

export function setLang(lang) {
  if (lang !== "ar" && lang !== "en") return;
  currentLang = lang;
  localStorage.setItem("mm_lang", lang);
  applyDirection();
  applyI18n();
  document.dispatchEvent(new CustomEvent("mm:langchange"));
}

// بيطبّق النصوص على أي عنصر معلّم بـ data-i18n أو data-i18n-placeholder
export function applyI18n(root) {
  const scope = root || document;
  scope.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  scope.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
  });
  const titleEl = document.querySelector("title[data-i18n-title]");
  if (titleEl) {
    document.title = `${t(titleEl.getAttribute("data-i18n-title"))} · Media Made`;
  }
}
